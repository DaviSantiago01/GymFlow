-- A RN03 foi esclarecida pelo usuário: uma avaliação por treino do aluno.
-- Avaliações anteriores permanecem sem treino, sem inventar histórico retroativo.
CREATE TABLE TRN_TREINO (
    TRN_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    PRO_ID BIGINT NOT NULL REFERENCES PRO_PROFESSOR(PRO_ID),
    TRN_DESCRICAO VARCHAR(120) NOT NULL,
    TRN_INICIO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    TRN_TERMINO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    TRN_CONCLUIDO BOOLEAN NOT NULL DEFAULT FALSE,
    TRN_DEMONSTRACAO BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT CK_TRN_PERIODO CHECK (TRN_TERMINO > TRN_INICIO),
    CONSTRAINT UK_TRN_ALUNO_PROFESSOR UNIQUE(TRN_ID,ALU_ID,PRO_ID)
);
CREATE INDEX IX_TRN_HISTORICO ON TRN_TREINO(ALU_ID,TRN_CONCLUIDO,TRN_INICIO,TRN_ID);
CREATE TABLE VAT_TREINO_AVALIADO (TRN_ID BIGINT PRIMARY KEY REFERENCES TRN_TREINO(TRN_ID));
ALTER TABLE AVP_AVALIACAO_PROFESSOR DROP CONSTRAINT FK_AVP_PARTICIPACAO;
ALTER TABLE AVP_AVALIACAO_PROFESSOR DROP CONSTRAINT UK_AVP_ALUNO_PROFESSOR;
ALTER TABLE AVP_AVALIACAO_PROFESSOR ADD TRN_ID BIGINT;
ALTER TABLE AVP_AVALIACAO_PROFESSOR ADD CONSTRAINT UK_AVP_TREINO UNIQUE(TRN_ID);
ALTER TABLE AVP_AVALIACAO_PROFESSOR ADD CONSTRAINT FK_AVP_TREINO FOREIGN KEY(TRN_ID,ALU_ID,PRO_ID) REFERENCES TRN_TREINO(TRN_ID,ALU_ID,PRO_ID);
ALTER TABLE AVP_AVALIACAO_PROFESSOR ADD CONSTRAINT FK_AVP_TREINO_AVALIADO FOREIGN KEY(TRN_ID) REFERENCES VAT_TREINO_AVALIADO(TRN_ID);
