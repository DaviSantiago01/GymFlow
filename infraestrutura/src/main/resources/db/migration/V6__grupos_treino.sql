CREATE TABLE GRT_GRUPO_TREINO (
 GRT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 GRT_NOME VARCHAR(60) NOT NULL CHECK(CHAR_LENGTH(TRIM(GRT_NOME)) BETWEEN 1 AND 60),
 ALU_ORGANIZADOR BIGINT NOT NULL, ACD_ID BIGINT NOT NULL REFERENCES ACD_ACADEMIA(ACD_ID),
 GRT_CRIACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL, GRT_ENCERRAMENTO TIMESTAMP(9) WITH TIME ZONE,
 FOREIGN KEY(ALU_ORGANIZADOR,ACD_ID) REFERENCES ALU_ALUNO(ALU_ID,ACD_ID), UNIQUE(GRT_ID,ACD_ID),
 CHECK(GRT_ENCERRAMENTO IS NULL OR GRT_ENCERRAMENTO>=GRT_CRIACAO)
);
CREATE TABLE PGR_PARTICIPACAO_GRUPO (
 PGR_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 GRT_ID BIGINT NOT NULL, ALU_ID BIGINT NOT NULL, ACD_ID BIGINT NOT NULL,
 PGR_ENTRADA TIMESTAMP(9) WITH TIME ZONE NOT NULL, PGR_SAIDA TIMESTAMP(9) WITH TIME ZONE,
 PGR_ATIVO BIGINT GENERATED ALWAYS AS (CASE WHEN PGR_SAIDA IS NULL THEN ALU_ID ELSE NULL END),
 FOREIGN KEY(GRT_ID,ACD_ID) REFERENCES GRT_GRUPO_TREINO(GRT_ID,ACD_ID),
 FOREIGN KEY(ALU_ID,ACD_ID) REFERENCES ALU_ALUNO(ALU_ID,ACD_ID), UNIQUE(GRT_ID,PGR_ATIVO),
 CHECK(PGR_SAIDA IS NULL OR PGR_SAIDA>=PGR_ENTRADA)
);
CREATE INDEX IX_PGR_ALUNO ON PGR_PARTICIPACAO_GRUPO(ALU_ID,GRT_ID,PGR_SAIDA);
CREATE TABLE CGR_CONVITE_GRUPO (
 CGR_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 GRT_ID BIGINT NOT NULL, ALU_ID BIGINT NOT NULL, ACD_ID BIGINT NOT NULL,
 CGR_SITUACAO VARCHAR(12) NOT NULL CHECK(CGR_SITUACAO IN ('PENDENTE','ACEITO','RECUSADO','CANCELADO')),
 CGR_ENVIO TIMESTAMP(9) WITH TIME ZONE NOT NULL, CGR_RESPOSTA TIMESTAMP(9) WITH TIME ZONE,
 CGR_PENDENTE BIGINT GENERATED ALWAYS AS (CASE WHEN CGR_SITUACAO='PENDENTE' THEN ALU_ID ELSE NULL END),
 FOREIGN KEY(GRT_ID,ACD_ID) REFERENCES GRT_GRUPO_TREINO(GRT_ID,ACD_ID),
 FOREIGN KEY(ALU_ID,ACD_ID) REFERENCES ALU_ALUNO(ALU_ID,ACD_ID), UNIQUE(GRT_ID,CGR_PENDENTE),
 CHECK((CGR_SITUACAO='PENDENTE' AND CGR_RESPOSTA IS NULL) OR (CGR_SITUACAO<>'PENDENTE' AND CGR_RESPOSTA IS NOT NULL))
);
CREATE INDEX IX_CGR_RECEBIDOS ON CGR_CONVITE_GRUPO(ALU_ID,CGR_ENVIO);
CREATE TABLE TGR_TREINO_GRUPO (
 TGR_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 GRT_ID BIGINT NOT NULL REFERENCES GRT_GRUPO_TREINO(GRT_ID),
 TGR_INICIO TIMESTAMP(9) WITH TIME ZONE NOT NULL, TGR_PRAZO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
 TGR_CRIACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL, TGR_CANCELAMENTO TIMESTAMP(9) WITH TIME ZONE,
 CHECK(TGR_CRIACAO<TGR_PRAZO AND TGR_PRAZO<TGR_INICIO)
);
CREATE INDEX IX_TGR_AGENDA ON TGR_TREINO_GRUPO(GRT_ID,TGR_INICIO);
CREATE INDEX IX_TGR_PRAZO ON TGR_TREINO_GRUPO(TGR_PRAZO);
CREATE TABLE CTR_CONVITE_TREINO (
 CTR_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 TGR_ID BIGINT NOT NULL REFERENCES TGR_TREINO_GRUPO(TGR_ID), ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
 CTR_SITUACAO VARCHAR(12) NOT NULL CHECK(CTR_SITUACAO IN ('PENDENTE','CONFIRMADO','RECUSADO','EXPIRADO','CANCELADO')),
 CTR_CRIACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL, CTR_RESPOSTA TIMESTAMP(9) WITH TIME ZONE,
 CTR_CANCELAMENTO TIMESTAMP(9) WITH TIME ZONE, CTR_MOTIVO VARCHAR(30),
 UNIQUE(TGR_ID,ALU_ID),
 CHECK((CTR_SITUACAO='CANCELADO' AND CTR_CANCELAMENTO IS NOT NULL AND CTR_MOTIVO IS NOT NULL) OR (CTR_SITUACAO<>'CANCELADO' AND CTR_CANCELAMENTO IS NULL AND CTR_MOTIVO IS NULL)),
 CHECK(CTR_SITUACAO NOT IN ('CONFIRMADO','RECUSADO') OR CTR_RESPOSTA IS NOT NULL)
);
CREATE INDEX IX_CTR_ALUNO ON CTR_CONVITE_TREINO(ALU_ID,TGR_ID);
CREATE INDEX IX_CTR_PENDENTES ON CTR_CONVITE_TREINO(CTR_SITUACAO,TGR_ID);
