CREATE TABLE ALU_ALUNO (
    ALU_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_USUARIO VARCHAR(100) NOT NULL UNIQUE,
    ALU_NOME VARCHAR(100) NOT NULL
);
CREATE TABLE USU_CREDENCIAL (
    ALU_USUARIO VARCHAR(100) PRIMARY KEY REFERENCES ALU_ALUNO(ALU_USUARIO),
    USU_SENHA VARCHAR(255) NOT NULL,
    USU_ATIVO BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE ARM_ARMARIO (
    ARM_CODIGO VARCHAR(5) PRIMARY KEY,
    ARM_LOCALIZACAO VARCHAR(150) NOT NULL,
    ARM_DESCRICAO VARCHAR(250) NOT NULL
);
CREATE TABLE RSV_RESERVA_ARMARIO (
    RSV_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    ARM_CODIGO VARCHAR(5) NOT NULL REFERENCES ARM_ARMARIO(ARM_CODIGO),
    RSV_CONFIRMACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    RSV_TERMINO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    RSV_ENCERRAMENTO TIMESTAMP(9) WITH TIME ZONE,
    RSV_SITUACAO VARCHAR(20) NOT NULL,
    -- Colunas calculadas pelo H2: não há um segundo estado controlado pela aplicação.
    RSV_ALUNO_ATIVO BIGINT GENERATED ALWAYS AS (CASE WHEN RSV_SITUACAO = 'ATIVA' THEN ALU_ID END),
    RSV_ARMARIO_ATIVO VARCHAR(5) GENERATED ALWAYS AS (CASE WHEN RSV_SITUACAO = 'ATIVA' THEN ARM_CODIGO END),
    CONSTRAINT UK_RSV_ALUNO_ATIVO UNIQUE (RSV_ALUNO_ATIVO),
    CONSTRAINT UK_RSV_ARMARIO_ATIVO UNIQUE (RSV_ARMARIO_ATIVO),
    CONSTRAINT CK_RSV_SITUACAO CHECK (RSV_SITUACAO IN ('ATIVA','CANCELADA','ENCERRADA','VENCIDA')),
    CONSTRAINT CK_RSV_PRAZO CHECK (RSV_TERMINO = DATEADD('HOUR',3,RSV_CONFIRMACAO)),
    CONSTRAINT CK_RSV_ENCERRAMENTO CHECK (
        (RSV_SITUACAO = 'ATIVA' AND RSV_ENCERRAMENTO IS NULL) OR
        (RSV_SITUACAO <> 'ATIVA' AND RSV_ENCERRAMENTO IS NOT NULL AND
         RSV_ENCERRAMENTO >= RSV_CONFIRMACAO AND RSV_ENCERRAMENTO <= RSV_TERMINO)),
    CONSTRAINT CK_RSV_VENCIMENTO CHECK (RSV_SITUACAO <> 'VENCIDA' OR RSV_ENCERRAMENTO = RSV_TERMINO)
);
CREATE INDEX IX_RSV_VENCIMENTO ON RSV_RESERVA_ARMARIO(RSV_SITUACAO,RSV_TERMINO);
CREATE INDEX IX_RSV_HISTORICO ON RSV_RESERVA_ARMARIO(ALU_ID,RSV_CONFIRMACAO);
