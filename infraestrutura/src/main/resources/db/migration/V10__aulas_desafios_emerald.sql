-- Funcionalidades Emerald Fit: aulas, inscrições, desafios, avaliações e notificações.
-- Referências usam os cadastros de alunos e profissionais existentes.
CREATE TABLE AUL_AULA (
    AUL_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUL_TITULO VARCHAR(100) NOT NULL,
    AUL_MODALIDADE VARCHAR(60) NOT NULL,
    AUL_DESCRICAO VARCHAR(500),
    AUL_DATA DATE NOT NULL,
    AUL_INICIO TIME NOT NULL,
    AUL_FIM TIME NOT NULL,
    AUL_LIMITE INT NOT NULL,
    AUL_STATUS VARCHAR(12) NOT NULL DEFAULT 'ABERTA',
    PRF_ID BIGINT NOT NULL REFERENCES PRF_PROFISSIONAL(PRF_ID),
    AUL_CRIACAO TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_AUL_HORARIO CHECK (AUL_INICIO < AUL_FIM),
    CONSTRAINT CK_AUL_LIMITE CHECK (AUL_LIMITE > 0),
    CONSTRAINT CK_AUL_STATUS CHECK (REGEXP_LIKE(AUL_STATUS, '^(ABERTA|CANCELADA)$'))
);
CREATE INDEX IX_AUL_DATA ON AUL_AULA(AUL_DATA,AUL_INICIO,AUL_STATUS);
CREATE INDEX IX_AUL_PROFESSOR ON AUL_AULA(PRF_ID,AUL_DATA,AUL_INICIO);

CREATE TABLE AIN_INSCRICAO_AULA (
    AIN_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUL_ID BIGINT NOT NULL REFERENCES AUL_AULA(AUL_ID),
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    AIN_STATUS VARCHAR(24) NOT NULL,
    AIN_REGISTRO TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    AIN_CANCELAMENTO TIMESTAMP WITH TIME ZONE,
    CONSTRAINT UK_AIN_AULA_ALUNO UNIQUE (AUL_ID,ALU_ID),
    CONSTRAINT CK_AIN_STATUS CHECK (REGEXP_LIKE(AIN_STATUS, '^(AGENDADO|CONCLUIDO|CANCELADO|CANCELADO_PELA_ACADEMIA)$'))
);
CREATE INDEX IX_AIN_ALUNO ON AIN_INSCRICAO_AULA(ALU_ID,AIN_REGISTRO);

CREATE TABLE NOT_NOTIFICACAO_AULA (
    NOT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUL_ID BIGINT NOT NULL REFERENCES AUL_AULA(AUL_ID),
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    NOT_MENSAGEM VARCHAR(300) NOT NULL,
    NOT_REGISTRO TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    NOT_LIDA BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE DES_DESAFIO (
    DES_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DES_TITULO VARCHAR(100) NOT NULL,
    DES_INDICADOR VARCHAR(20) NOT NULL,
    DES_INICIO DATE NOT NULL,
    DES_FIM DATE NOT NULL,
    DES_STATUS VARCHAR(12) NOT NULL DEFAULT 'ABERTO',
    DES_CRIACAO TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_DES_VIGENCIA CHECK (DES_FIM >= DATEADD('DAY', 7, DES_INICIO)),
    CONSTRAINT CK_DES_INDICADOR CHECK (REGEXP_LIKE(DES_INDICADOR, '^(PESO|CINTURA|GORDURA_CORPORAL)$')),
    CONSTRAINT CK_DES_STATUS CHECK (REGEXP_LIKE(DES_STATUS, '^(ABERTO|ENCERRADO)$'))
);

CREATE TABLE DAF_AVALIACAO_DESAFIO (
    DAF_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DES_ID BIGINT NOT NULL REFERENCES DES_DESAFIO(DES_ID),
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    PRF_ID BIGINT NOT NULL REFERENCES PRF_PROFISSIONAL(PRF_ID),
    DAF_TIPO VARCHAR(16) NOT NULL,
    DAF_PESO DECIMAL(6,2) NOT NULL,
    DAF_CINTURA DECIMAL(6,2) NOT NULL,
    DAF_GORDURA DECIMAL(5,2) NOT NULL,
    DAF_REGISTRO TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UK_DAF_REFERENCIA UNIQUE (DAF_ID,DES_ID,ALU_ID),
    CONSTRAINT CK_DAF_TIPO CHECK (REGEXP_LIKE(DAF_TIPO, '^(INICIAL|INTERMEDIARIA|FINAL)$')),
    CONSTRAINT CK_DAF_VALORES CHECK (DAF_PESO > 0 AND DAF_CINTURA > 0 AND DAF_GORDURA > 0 AND DAF_GORDURA < 100)
);
CREATE INDEX IX_DAF_DESAFIO_ALUNO ON DAF_AVALIACAO_DESAFIO(DES_ID,ALU_ID,DAF_REGISTRO);

CREATE TABLE DIN_INSCRICAO_DESAFIO (
    DIN_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DES_ID BIGINT NOT NULL REFERENCES DES_DESAFIO(DES_ID),
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    DIN_INDICADOR VARCHAR(20) NOT NULL,
    DIN_META DECIMAL(8,2) NOT NULL,
    DIN_AVALIACAO_INICIAL BIGINT NOT NULL,
    DIN_REGISTRO TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UK_DIN_DESAFIO_ALUNO UNIQUE (DES_ID,ALU_ID),
    CONSTRAINT FK_DIN_AVALIACAO_INICIAL FOREIGN KEY (DIN_AVALIACAO_INICIAL,DES_ID,ALU_ID)
        REFERENCES DAF_AVALIACAO_DESAFIO(DAF_ID,DES_ID,ALU_ID),
    CONSTRAINT CK_DIN_META CHECK (DIN_META > 0),
    CONSTRAINT CK_DIN_INDICADOR CHECK (REGEXP_LIKE(DIN_INDICADOR, '^(PESO|CINTURA|GORDURA_CORPORAL)$'))
);
