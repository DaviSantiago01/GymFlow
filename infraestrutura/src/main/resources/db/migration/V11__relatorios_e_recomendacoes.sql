-- Relatórios de desempenho da academia (F015) e recomendações personalizadas (F016).
-- As entradas vêm do controle de acesso (RAC_REGISTRO_ACESSO, F006) e o CPF e o telefone, do cadastro do aluno (F005).
-- Nenhuma tabela existente é alterada. As listas de valores usam REGEXP_LIKE pelo mesmo motivo descrito na V7.

-- Trancamentos temporários de uma adesão. O aluno trancado não conta como ativo nem como evasão.
CREATE TABLE TRC_TRANCAMENTO (
    TRC_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADP_ID BIGINT NOT NULL REFERENCES ADP_ADESAO_PLANO(ADP_ID),
    TRC_INICIO DATE NOT NULL,
    TRC_FIM DATE NOT NULL,
    CONSTRAINT CK_TRC_PERIODO CHECK (TRC_FIM >= TRC_INICIO)
);
CREATE INDEX IX_TRC_ADESAO ON TRC_TRANCAMENTO(ADP_ID,TRC_INICIO);

CREATE TABLE EST_USO_ESTACIONAMENTO (
    EST_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT REFERENCES ALU_ALUNO(ALU_ID),
    EST_ENTRADA TIMESTAMP NOT NULL,
    EST_SAIDA TIMESTAMP NOT NULL,
    CONSTRAINT CK_EST_PERIODO CHECK (EST_SAIDA > EST_ENTRADA)
);
CREATE INDEX IX_EST_ENTRADA ON EST_USO_ESTACIONAMENTO(EST_ENTRADA);

CREATE TABLE AUC_AULA_COLETIVA (
    AUC_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUC_NOME VARCHAR(60) NOT NULL,
    AUC_MODALIDADE VARCHAR(40) NOT NULL,
    AUC_INSTRUTOR VARCHAR(100) NOT NULL,
    AUC_SALA VARCHAR(40) NOT NULL,
    AUC_DIA VARCHAR(10) NOT NULL,
    AUC_INICIO VARCHAR(8) NOT NULL,
    AUC_FIM VARCHAR(8) NOT NULL,
    -- Horários locais no formato HH:mm:ss, sem conversão de fuso.
    AUC_CAPACIDADE INT NOT NULL,
    AUC_NIVEL VARCHAR(15) NOT NULL,
    AUC_IMPACTO VARCHAR(10) NOT NULL,
    -- Listas separadas por vírgula: objetivos atendidos e regiões corporais contraindicadas.
    AUC_OBJETIVOS VARCHAR(60) NOT NULL,
    AUC_CONTRAINDICACOES VARCHAR(120) NOT NULL DEFAULT '',
    AUC_ATIVA BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT CK_AUC_DIA CHECK (REGEXP_LIKE(AUC_DIA, '^(SEGUNDA|TERCA|QUARTA|QUINTA|SEXTA|SABADO|DOMINGO)$')),
    CONSTRAINT CK_AUC_HORARIO CHECK (AUC_INICIO < AUC_FIM),
    CONSTRAINT CK_AUC_CAPACIDADE CHECK (AUC_CAPACIDADE > 0),
    CONSTRAINT CK_AUC_NIVEL CHECK (REGEXP_LIKE(AUC_NIVEL, '^(INICIANTE|INTERMEDIARIO|AVANCADO)$')),
    CONSTRAINT CK_AUC_IMPACTO CHECK (REGEXP_LIKE(AUC_IMPACTO, '^(BAIXO|MODERADO|ALTO)$'))
);

CREATE TABLE IAC_INSCRICAO_AULA (
    IAC_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUC_ID BIGINT NOT NULL REFERENCES AUC_AULA_COLETIVA(AUC_ID),
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    IAC_DATA TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    CONSTRAINT UK_IAC_AULA_ALUNO UNIQUE (AUC_ID,ALU_ID)
);
CREATE INDEX IX_IAC_ALUNO ON IAC_INSCRICAO_AULA(ALU_ID);

-- Classificação dos exercícios para as recomendações. O grupo muscular é a categoria do próprio exercício.
CREATE TABLE CEX_CLASSIFICACAO_EXERCICIO (
    EXE_ID BIGINT PRIMARY KEY REFERENCES EXE_EXERCICIO(EXE_ID),
    CEX_NIVEL VARCHAR(15) NOT NULL,
    CEX_OBJETIVOS VARCHAR(60) NOT NULL,
    CEX_CONTRAINDICACOES VARCHAR(120) NOT NULL DEFAULT '',
    CONSTRAINT CK_CEX_NIVEL CHECK (REGEXP_LIKE(CEX_NIVEL, '^(INICIANTE|INTERMEDIARIO|AVANCADO)$'))
);

CREATE TABLE MAC_META_ACADEMIA (
    MAC_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MAC_INDICADOR VARCHAR(30) NOT NULL,
    MAC_VALOR_DESEJADO DECIMAL(12,2) NOT NULL,
    MAC_INICIO DATE NOT NULL,
    MAC_FIM DATE NOT NULL,
    MAC_SITUACAO VARCHAR(12) NOT NULL,
    MAC_CRIACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    MAC_RESPONSAVEL VARCHAR(100) NOT NULL,
    CONSTRAINT CK_MAC_VALOR CHECK (MAC_VALOR_DESEJADO >= 0),
    CONSTRAINT CK_MAC_PERIODO CHECK (MAC_FIM >= MAC_INICIO),
    CONSTRAINT CK_MAC_SITUACAO CHECK (REGEXP_LIKE(MAC_SITUACAO, '^(ATIVA|ENCERRADA|SUBSTITUIDA)$'))
);
CREATE INDEX IX_MAC_INDICADOR ON MAC_META_ACADEMIA(MAC_INDICADOR,MAC_SITUACAO,MAC_INICIO);

-- Relatórios gerados. RLT_CONTEUDO guarda os valores calculados no momento da geração e nunca é recalculado.
CREATE TABLE RLT_RELATORIO (
    RLT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RLT_TIPO VARCHAR(30) NOT NULL,
    RLT_INICIO DATE NOT NULL,
    RLT_FIM DATE NOT NULL,
    RLT_AGRUPAMENTO VARCHAR(10) NOT NULL,
    RLT_COMPARAR BOOLEAN NOT NULL,
    RLT_FILTRO_PLANO BIGINT REFERENCES PLA_PLANO(PLA_ID),
    RLT_FILTRO_MODALIDADE VARCHAR(40),
    RLT_FILTRO_PERSONAL BIGINT REFERENCES PER_PERSONAL(PER_ID),
    RLT_FILTRO_AULA BIGINT REFERENCES AUC_AULA_COLETIVA(AUC_ID),
    RLT_GERACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    RLT_USUARIO VARCHAR(100) NOT NULL,
    RLT_USUARIO_NOME VARCHAR(100) NOT NULL,
    RLT_PERFIL VARCHAR(20) NOT NULL,
    RLT_VERSAO INT NOT NULL,
    RLT_ANTERIOR BIGINT REFERENCES RLT_RELATORIO(RLT_ID),
    RLT_SITUACAO VARCHAR(12) NOT NULL,
    RLT_CONTEUDO CLOB NOT NULL,
    CONSTRAINT CK_RLT_PERIODO CHECK (RLT_FIM >= RLT_INICIO),
    CONSTRAINT CK_RLT_AGRUPAMENTO CHECK (REGEXP_LIKE(RLT_AGRUPAMENTO, '^(DIA|SEMANA|MES)$')),
    CONSTRAINT CK_RLT_SITUACAO CHECK (REGEXP_LIKE(RLT_SITUACAO, '^(ATUAL|SUBSTITUIDO)$')),
    CONSTRAINT CK_RLT_VERSAO CHECK (RLT_VERSAO >= 1)
);
CREATE INDEX IX_RLT_GERACAO ON RLT_RELATORIO(RLT_GERACAO);
CREATE INDEX IX_RLT_USUARIO ON RLT_RELATORIO(RLT_USUARIO,RLT_GERACAO);

CREATE TABLE PFA_PERFIL_ALUNO (
    ALU_ID BIGINT PRIMARY KEY REFERENCES ALU_ALUNO(ALU_ID),
    PFA_OBJETIVO VARCHAR(15),
    PFA_NIVEL VARCHAR(15),
    PFA_DIAS VARCHAR(70),
    PFA_HORA_INICIO VARCHAR(8),
    PFA_HORA_FIM VARCHAR(8),
    PFA_CATEGORIAS_DESATIVADAS VARCHAR(120) NOT NULL DEFAULT '',
    PFA_ATUALIZACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    CONSTRAINT CK_PFA_OBJETIVO CHECK (PFA_OBJETIVO IS NULL OR REGEXP_LIKE(PFA_OBJETIVO, '^(HIPERTROFIA|EMAGRECIMENTO|CONDICIONAMENTO)$')),
    CONSTRAINT CK_PFA_NIVEL CHECK (PFA_NIVEL IS NULL OR REGEXP_LIKE(PFA_NIVEL, '^(INICIANTE|INTERMEDIARIO|AVANCADO)$')),
    CONSTRAINT CK_PFA_HORARIO CHECK (PFA_HORA_INICIO IS NULL OR PFA_HORA_FIM IS NULL OR PFA_HORA_INICIO < PFA_HORA_FIM)
);

CREATE TABLE RFI_RESTRICAO_FISICA (
    RFI_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES PFA_PERFIL_ALUNO(ALU_ID),
    RFI_INDICE INT NOT NULL,
    RFI_REGIAO VARCHAR(15) NOT NULL,
    RFI_DESCRICAO VARCHAR(250) NOT NULL,
    RFI_REGISTRO DATE NOT NULL
);
CREATE INDEX IX_RFI_ALUNO ON RFI_RESTRICAO_FISICA(ALU_ID,RFI_INDICE);

CREATE TABLE REC_RECOMENDACAO (
    REC_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    REC_CATEGORIA VARCHAR(25) NOT NULL,
    REC_CRITERIO VARCHAR(30) NOT NULL,
    REC_ITEM VARCHAR(60) NOT NULL,
    REC_TITULO VARCHAR(120) NOT NULL,
    REC_DESCRICAO VARCHAR(500) NOT NULL,
    REC_JUSTIFICATIVA VARCHAR(500) NOT NULL,
    PER_ID BIGINT REFERENCES PER_PERSONAL(PER_ID),
    PLT_ID BIGINT REFERENCES PLT_PLANO_TREINO(PLT_ID),
    EXE_ATUAL BIGINT REFERENCES EXE_EXERCICIO(EXE_ID),
    EXE_SUGERIDO BIGINT REFERENCES EXE_EXERCICIO(EXE_ID),
    REC_SERIES INT,
    REC_REPETICOES_MINIMAS INT,
    REC_REPETICOES_MAXIMAS INT,
    REC_CARGA DECIMAL(7,2),
    REC_INTERVALO_SEGUNDOS INT,
    AUC_ID BIGINT REFERENCES AUC_AULA_COLETIVA(AUC_ID),
    PLA_ID BIGINT REFERENCES PLA_PLANO(PLA_ID),
    REC_GERACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    REC_VALIDADE DATE NOT NULL,
    REC_SITUACAO VARCHAR(25) NOT NULL,
    REC_RESPOSTA TIMESTAMP(9) WITH TIME ZONE,
    REC_RESPONDENTE VARCHAR(100),
    REC_MOTIVO VARCHAR(250),
    REC_AJUSTE VARCHAR(250),
    PLT_GERADO BIGINT REFERENCES PLT_PLANO_TREINO(PLT_ID),
    REC_CIENCIA TIMESTAMP(9) WITH TIME ZONE,
    CONSTRAINT CK_REC_CATEGORIA CHECK (REGEXP_LIKE(REC_CATEGORIA, '^(ACOMPANHAMENTO_FISICO|FREQUENCIA_HORARIOS|AJUSTES_TREINO|AULAS_COLETIVAS|PLANOS_SERVICOS)$')),
    CONSTRAINT CK_REC_SITUACAO CHECK (REGEXP_LIKE(REC_SITUACAO, '^(AGUARDANDO_APROVACAO|PENDENTE|APROVADA|ACEITA|RECUSADA|REJEITADA|EXPIRADA)$')),
    CONSTRAINT CK_REC_RESPOSTA CHECK (REC_RESPOSTA IS NULL OR REC_RESPOSTA >= REC_GERACAO)
);
CREATE INDEX IX_REC_ALUNO ON REC_RECOMENDACAO(ALU_ID,REC_SITUACAO,REC_GERACAO);
CREATE INDEX IX_REC_ITEM ON REC_RECOMENDACAO(ALU_ID,REC_CATEGORIA,REC_ITEM);
CREATE INDEX IX_REC_PERSONAL ON REC_RECOMENDACAO(PER_ID,REC_SITUACAO);

-- Dados que fundamentam a recomendação, como os treinos registrados em cada semana.
CREATE TABLE REV_EVIDENCIA (
    REC_ID BIGINT NOT NULL REFERENCES REC_RECOMENDACAO(REC_ID),
    REV_INDICE INT NOT NULL,
    REV_ROTULO VARCHAR(40) NOT NULL,
    REV_VALOR DECIMAL(10,2) NOT NULL,
    REV_DESTAQUE BOOLEAN NOT NULL,
    PRIMARY KEY (REC_ID,REV_INDICE)
);
