CREATE TABLE PRO_PROFESSOR (
    PRO_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRO_NOME VARCHAR(100) NOT NULL,
    PRO_ESPECIALIDADE VARCHAR(120) NOT NULL,
    PRO_BIOGRAFIA VARCHAR(1000) NOT NULL,
    PRO_DEMONSTRACAO BOOLEAN NOT NULL DEFAULT FALSE
);
-- Guarda somente o par para a política conservadora de não recriação da RN03.
CREATE TABLE VAP_AVALIACAO_REALIZADA (
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    PRO_ID BIGINT NOT NULL REFERENCES PRO_PROFESSOR(PRO_ID),
    PRIMARY KEY (ALU_ID,PRO_ID)
);
CREATE TABLE AVP_AVALIACAO_PROFESSOR (
    AVP_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    PRO_ID BIGINT NOT NULL REFERENCES PRO_PROFESSOR(PRO_ID),
    AVP_AUXILIO INTEGER NOT NULL CHECK (AVP_AUXILIO BETWEEN 0 AND 5),
    AVP_PONTUALIDADE INTEGER NOT NULL CHECK (AVP_PONTUALIDADE BETWEEN 0 AND 5),
    AVP_POSTURA INTEGER NOT NULL CHECK (AVP_POSTURA BETWEEN 0 AND 5),
    AVP_DIDATICA INTEGER NOT NULL CHECK (AVP_DIDATICA BETWEEN 0 AND 5),
    AVP_ADEQUACAO INTEGER NOT NULL CHECK (AVP_ADEQUACAO BETWEEN 0 AND 5),
    AVP_COMENTARIO VARCHAR(500),
    AVP_CRIACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    AVP_ATUALIZACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    CONSTRAINT UK_AVP_ALUNO_PROFESSOR UNIQUE (ALU_ID,PRO_ID),
    CONSTRAINT FK_AVP_PARTICIPACAO FOREIGN KEY (ALU_ID,PRO_ID) REFERENCES VAP_AVALIACAO_REALIZADA(ALU_ID,PRO_ID),
    CONSTRAINT CK_AVP_DATAS CHECK (AVP_ATUALIZACAO >= AVP_CRIACAO)
);
CREATE INDEX IX_PRO_NOME ON PRO_PROFESSOR(PRO_NOME);
CREATE INDEX IX_AVP_RECENTES ON AVP_AVALIACAO_PROFESSOR(PRO_ID,AVP_CRIACAO,AVP_ID);
CREATE INDEX IX_AVP_AUTOR ON AVP_AVALIACAO_PROFESSOR(ALU_ID,AVP_CRIACAO,AVP_ID);
