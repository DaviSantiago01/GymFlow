CREATE TABLE PER_PERSONAL (
    PER_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PER_USUARIO VARCHAR(100) NOT NULL UNIQUE,
    PER_NOME VARCHAR(100) NOT NULL
);
CREATE TABLE PCD_CREDENCIAL_PERSONAL (
    PER_ID BIGINT PRIMARY KEY REFERENCES PER_PERSONAL(PER_ID),
    PCD_SENHA VARCHAR(255) NOT NULL,
    PCD_ATIVO BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE EXE_EXERCICIO (
    EXE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EXE_NOME VARCHAR(100) NOT NULL UNIQUE,
    EXE_CATEGORIA VARCHAR(20) NOT NULL,
    EXE_CARGA_MAXIMA DECIMAL(7,2) NOT NULL,
    EXE_INCREMENTO_CARGA DECIMAL(7,2)
);
CREATE TABLE PLT_PLANO_TREINO (
    PLT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    PER_ID BIGINT NOT NULL REFERENCES PER_PERSONAL(PER_ID),
    PLT_NOME VARCHAR(100) NOT NULL,
    PLT_FREQUENCIA_SEMANAL INT NOT NULL,
    PLT_SITUACAO VARCHAR(20) NOT NULL,
    PLT_VERSAO INT NOT NULL,
    PLT_PLANO_ANTERIOR BIGINT REFERENCES PLT_PLANO_TREINO(PLT_ID),
    PLT_CRIACAO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    PLT_ENCERRAMENTO TIMESTAMP(9) WITH TIME ZONE,
    -- Coluna calculada pelo H2: garante um único plano ativo por aluno.
    PLT_ALUNO_ATIVO BIGINT GENERATED ALWAYS AS (CASE WHEN PLT_SITUACAO = 'ATIVO' THEN ALU_ID END),
    CONSTRAINT UK_PLT_ALUNO_ATIVO UNIQUE (PLT_ALUNO_ATIVO)
);
CREATE INDEX IX_PLT_ALUNO ON PLT_PLANO_TREINO(ALU_ID,PLT_CRIACAO);
CREATE TABLE TRE_TREINO (
    TRE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLT_ID BIGINT NOT NULL REFERENCES PLT_PLANO_TREINO(PLT_ID),
    TRE_INDICE INT NOT NULL,
    TRE_NOME VARCHAR(60) NOT NULL,
    TRE_DIA VARCHAR(10) NOT NULL,
    TRE_OBJETIVO VARCHAR(20) NOT NULL,
    CONSTRAINT UK_TRE_PLANO_DIA UNIQUE (PLT_ID,TRE_DIA)
);
CREATE TABLE SRE_SERIE (
    TRE_ID BIGINT NOT NULL REFERENCES TRE_TREINO(TRE_ID),
    SRE_INDICE INT NOT NULL,
    EXE_ID BIGINT NOT NULL REFERENCES EXE_EXERCICIO(EXE_ID),
    SRE_QUANTIDADE INT NOT NULL,
    SRE_REPETICOES_MINIMAS INT NOT NULL,
    SRE_REPETICOES_MAXIMAS INT NOT NULL,
    SRE_CARGA DECIMAL(7,2) NOT NULL,
    SRE_INTERVALO_SEGUNDOS INT NOT NULL,
    PRIMARY KEY (TRE_ID,SRE_INDICE),
    CONSTRAINT UK_SRE_TREINO_EXERCICIO UNIQUE (TRE_ID,EXE_ID)
);
CREATE TABLE EXC_EXECUCAO_EXERCICIO (
    EXC_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    PLT_ID BIGINT NOT NULL REFERENCES PLT_PLANO_TREINO(PLT_ID),
    EXE_ID BIGINT NOT NULL REFERENCES EXE_EXERCICIO(EXE_ID),
    EXC_DIA VARCHAR(10) NOT NULL,
    EXC_DATA TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    EXC_SERIES INT NOT NULL,
    EXC_REPETICOES INT NOT NULL,
    EXC_CARGA DECIMAL(7,2) NOT NULL
);
CREATE INDEX IX_EXC_HISTORICO ON EXC_EXECUCAO_EXERCICIO(ALU_ID,EXE_ID,EXC_DATA);
CREATE TABLE AVF_AVALIACAO_FISICA (
    AVF_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    PER_ID BIGINT NOT NULL REFERENCES PER_PERSONAL(PER_ID),
    AVF_DATA DATE NOT NULL,
    AVF_PESO DECIMAL(6,2) NOT NULL,
    AVF_ALTURA DECIMAL(6,2) NOT NULL,
    AVF_IMC DECIMAL(6,2) NOT NULL,
    AVF_SITUACAO VARCHAR(20) NOT NULL,
    AVF_VERSAO INT NOT NULL,
    AVF_AVALIACAO_ANTERIOR BIGINT REFERENCES AVF_AVALIACAO_FISICA(AVF_ID),
    AVF_REGISTRO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    -- Coluna calculada pelo H2: impede duas avaliações válidas do aluno na mesma data.
    AVF_ALUNO_VALIDA BIGINT GENERATED ALWAYS AS (CASE WHEN AVF_SITUACAO = 'VALIDA' THEN ALU_ID END),
    CONSTRAINT UK_AVF_ALUNO_DATA UNIQUE (AVF_ALUNO_VALIDA,AVF_DATA)
);
CREATE INDEX IX_AVF_ALUNO ON AVF_AVALIACAO_FISICA(ALU_ID,AVF_DATA);
CREATE TABLE MDC_MEDIDA_CORPORAL (
    AVF_ID BIGINT NOT NULL REFERENCES AVF_AVALIACAO_FISICA(AVF_ID),
    MDC_INDICE INT NOT NULL,
    MDC_INDICADOR VARCHAR(20) NOT NULL,
    MDC_VALOR DECIMAL(6,2) NOT NULL,
    PRIMARY KEY (AVF_ID,MDC_INDICE)
);
CREATE TABLE MET_META (
    MET_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    PER_ID BIGINT NOT NULL REFERENCES PER_PERSONAL(PER_ID),
    MET_INDICADOR VARCHAR(20) NOT NULL,
    MET_VALOR_INICIAL DECIMAL(6,2) NOT NULL,
    MET_VALOR_DESEJADO DECIMAL(6,2) NOT NULL,
    MET_INICIO DATE NOT NULL,
    MET_FIM DATE NOT NULL,
    AVF_ID BIGINT NOT NULL REFERENCES AVF_AVALIACAO_FISICA(AVF_ID),
    MET_SITUACAO VARCHAR(20) NOT NULL,
    MET_DATA_ATINGIDA DATE
);
CREATE INDEX IX_MET_ALUNO ON MET_META(ALU_ID,MET_INDICADOR,MET_SITUACAO);
