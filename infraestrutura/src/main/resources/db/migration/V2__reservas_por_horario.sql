UPDATE RSV_RESERVA_ARMARIO SET RSV_INICIO = RSV_CONFIRMACAO;
ALTER TABLE RSV_RESERVA_ARMARIO ALTER COLUMN RSV_INICIO SET NOT NULL;
ALTER TABLE RSV_RESERVA_ARMARIO DROP CONSTRAINT CK_RSV_PRAZO;
ALTER TABLE RSV_RESERVA_ARMARIO DROP CONSTRAINT UK_RSV_ARMARIO_ATIVO;
ALTER TABLE RSV_RESERVA_ARMARIO DROP COLUMN RSV_ARMARIO_ATIVO;
ALTER TABLE RSV_RESERVA_ARMARIO ADD CONSTRAINT CK_RSV_PRAZO CHECK (
    RSV_INICIO >= RSV_CONFIRMACAO AND RSV_TERMINO IN (
        DATEADD('HOUR',1,RSV_INICIO), DATEADD('HOUR',2,RSV_INICIO), DATEADD('HOUR',3,RSV_INICIO)));
ALTER TABLE RSV_RESERVA_ARMARIO ADD CONSTRAINT CK_RSV_USO CHECK (
    RSV_SITUACAO <> 'ENCERRADA' OR RSV_ENCERRAMENTO >= RSV_INICIO);
