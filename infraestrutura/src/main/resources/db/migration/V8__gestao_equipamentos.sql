create table EQP_EQUIPAMENTO (
    EQP_ID bigint generated by default as identity primary key,
    EQP_PATRIMONIO varchar(24) not null,
    EQP_SERIE varchar(40),
    EQP_NOME varchar(100) not null,
    EQP_TIPO varchar(20) not null,
    EQP_MARCA varchar(60) not null,
    EQP_MODELO varchar(60) not null,
    EQP_AQUISICAO date not null,
    EQP_AREA varchar(20) not null,
    EQP_SITUACAO varchar(20) not null,
    EQP_PERIODICIDADE integer not null,
    EQP_ULTIMA_INSPECAO date,
    constraint UK_EQP_PATRIMONIO unique (EQP_PATRIMONIO),
    constraint UK_EQP_SERIE unique (EQP_SERIE),
    constraint CK_EQP_PERIODICIDADE check (EQP_PERIODICIDADE > 0)
);

create table REQ_REGISTRO_EQUIPAMENTO (
    REQ_ID bigint generated by default as identity primary key,
    EQP_ID bigint not null references EQP_EQUIPAMENTO(EQP_ID),
    REQ_DATA date not null,
    REQ_RESPONSAVEL varchar(100) not null,
    REQ_AREA_ANTERIOR varchar(20) not null,
    REQ_AREA_NOVA varchar(20) not null,
    REQ_SITUACAO_ANTERIOR varchar(20) not null,
    REQ_SITUACAO_NOVA varchar(20) not null,
    REQ_RESULTADO varchar(24),
    REQ_OBSERVACAO varchar(800)
);
create index IX_REQ_REFERENCIA on REQ_REGISTRO_EQUIPAMENTO (EQP_ID);

create table PEQ_PROBLEMA_EQUIPAMENTO (
    PEQ_ID bigint generated by default as identity primary key,
    EQP_ID bigint not null references EQP_EQUIPAMENTO(EQP_ID),
    PEQ_TITULO varchar(100) not null,
    PEQ_RELATO varchar(800) not null,
    PEQ_GRAVIDADE varchar(10) not null,
    PEQ_RISCO boolean not null,
    PEQ_EVIDENCIA varchar(180),
    PEQ_DATA_RELATO date not null,
    PEQ_RESPONSAVEL varchar(100) not null,
    PEQ_SITUACAO varchar(12) not null,
    PEQ_DATA_ENCERRAMENTO date,
    PEQ_DESFECHO varchar(800)
);
create index IX_PEQ_REFERENCIA on PEQ_PROBLEMA_EQUIPAMENTO (EQP_ID);

create table OMT_ORDEM_MANUTENCAO (
    OMT_ID bigint generated by default as identity primary key,
    PEQ_ID bigint not null references PEQ_PROBLEMA_EQUIPAMENTO(PEQ_ID),
    OMT_TECNICO varchar(100) not null,
    OMT_DIAGNOSTICO varchar(800) not null,
    OMT_ABERTURA date not null,
    OMT_RESPONSAVEL varchar(100) not null,
    OMT_SITUACAO varchar(12) not null,
    OMT_INICIO date,
    OMT_TERMINO date,
    OMT_CUSTO_ESTIMADO decimal(12,2),
    OMT_CUSTO_REAL decimal(12,2),
    OMT_SERVICO_EXECUTADO varchar(800),
    OMT_JUSTIFICATIVA varchar(800),
    OMT_PROBLEMA_ATIVO bigint generated always as (case when OMT_SITUACAO in ('ABERTA','EM_ANDAMENTO') then PEQ_ID else null end),
    constraint UK_OMT_PROBLEMA_ATIVO unique (OMT_PROBLEMA_ATIVO),
    constraint CK_OMT_CUSTOS check (OMT_CUSTO_ESTIMADO >= 0 and OMT_CUSTO_REAL >= 0)
);
create index IX_OMT_REFERENCIA on OMT_ORDEM_MANUTENCAO (PEQ_ID);
