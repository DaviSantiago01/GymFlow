-- F005: dados cadastrais, situação e histórico de alterações do aluno.
-- F006: registros de entrada e saída da academia.
-- Os alunos já existentes (autocadastro F002) permanecem válidos: os dados cadastrais são opcionais na tabela e
-- passam a ser exigidos quando a administração cadastra ou altera o aluno.
-- As listas de valores usam REGEXP_LIKE em vez de IN pelo mesmo motivo descrito em V7.

ALTER TABLE ALU_ALUNO ADD COLUMN ALU_CPF VARCHAR(11);
ALTER TABLE ALU_ALUNO ADD COLUMN ALU_NASCIMENTO DATE;
ALTER TABLE ALU_ALUNO ADD COLUMN ALU_EMAIL VARCHAR(100);
ALTER TABLE ALU_ALUNO ADD COLUMN ALU_TELEFONE VARCHAR(20);
ALTER TABLE ALU_ALUNO ADD COLUMN ALU_ENDERECO VARCHAR(200);
ALTER TABLE ALU_ALUNO ADD COLUMN ALU_RESPONSAVEL_NOME VARCHAR(100);
ALTER TABLE ALU_ALUNO ADD COLUMN ALU_RESPONSAVEL_CPF VARCHAR(11);
ALTER TABLE ALU_ALUNO ADD COLUMN ALU_RESPONSAVEL_TELEFONE VARCHAR(20);
ALTER TABLE ALU_ALUNO ADD COLUMN ALU_ATIVO BOOLEAN DEFAULT TRUE NOT NULL;
ALTER TABLE ALU_ALUNO ADD COLUMN ALU_BLOQUEIO_MOTIVO VARCHAR(250);
ALTER TABLE ALU_ALUNO ADD COLUMN ALU_BLOQUEIO_INICIO TIMESTAMP(9) WITH TIME ZONE;

-- Índices únicos aceitam vários NULL: só os alunos com CPF ou e-mail informados são comparados.
ALTER TABLE ALU_ALUNO ADD CONSTRAINT UK_ALU_CPF UNIQUE (ALU_CPF);
ALTER TABLE ALU_ALUNO ADD CONSTRAINT UK_ALU_EMAIL UNIQUE (ALU_EMAIL);
ALTER TABLE ALU_ALUNO ADD CONSTRAINT CK_ALU_RESPONSAVEL CHECK (
    (ALU_RESPONSAVEL_NOME IS NULL AND ALU_RESPONSAVEL_CPF IS NULL) OR
    (ALU_RESPONSAVEL_NOME IS NOT NULL AND ALU_RESPONSAVEL_CPF IS NOT NULL));
ALTER TABLE ALU_ALUNO ADD CONSTRAINT CK_ALU_BLOQUEIO CHECK (
    (ALU_BLOQUEIO_MOTIVO IS NULL AND ALU_BLOQUEIO_INICIO IS NULL) OR
    (ALU_BLOQUEIO_MOTIVO IS NOT NULL AND ALU_BLOQUEIO_INICIO IS NOT NULL));

CREATE TABLE AHI_ALUNO_HISTORICO (
    AHI_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    AHI_INSTANTE TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    AHI_TIPO VARCHAR(20) NOT NULL,
    AHI_DESCRICAO VARCHAR(250) NOT NULL,
    AHI_RESPONSAVEL VARCHAR(100) NOT NULL,
    CONSTRAINT CK_AHI_TIPO CHECK (REGEXP_LIKE(AHI_TIPO, '^(CADASTRO|ALTERACAO|BLOQUEIO|DESBLOQUEIO|DESATIVACAO|REATIVACAO)$'))
);
CREATE INDEX IX_AHI_ALUNO ON AHI_ALUNO_HISTORICO(ALU_ID,AHI_INSTANTE);

CREATE TABLE RAC_REGISTRO_ACESSO (
    RAC_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    RAC_ENTRADA TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    RAC_SAIDA TIMESTAMP(9) WITH TIME ZONE,
    RAC_VERIFICAR BOOLEAN DEFAULT FALSE NOT NULL,
    -- Coluna calculada pelo H2: no máximo uma entrada sem saída por aluno.
    RAC_ALUNO_PRESENTE BIGINT GENERATED ALWAYS AS (CASE WHEN RAC_SAIDA IS NULL THEN ALU_ID END),
    CONSTRAINT UK_RAC_ALUNO_PRESENTE UNIQUE (RAC_ALUNO_PRESENTE),
    CONSTRAINT CK_RAC_SAIDA CHECK (RAC_SAIDA IS NULL OR RAC_SAIDA >= RAC_ENTRADA)
);
CREATE INDEX IX_RAC_ALUNO ON RAC_REGISTRO_ACESSO(ALU_ID,RAC_ENTRADA);
CREATE INDEX IX_RAC_ENTRADA ON RAC_REGISTRO_ACESSO(RAC_ENTRADA);
