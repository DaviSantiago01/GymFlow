-- Gerenciamento de planos e mensalidades, de professores e personal trainers, e conta de administrador.
-- Nenhuma tabela existente é alterada.
-- As listas de valores usam REGEXP_LIKE em vez de IN: no H2 2.4, um CHECK com IN (inclusive o gerado a partir de
-- comparações com OR) guarda a sessão que o criou e falha depois que essa conexão é fechada, como no banco embutido
-- sem pool usado em @DataJpaTest.

CREATE TABLE ADM_ADMINISTRADOR (
    ADM_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADM_USUARIO VARCHAR(100) NOT NULL UNIQUE,
    ADM_NOME VARCHAR(100) NOT NULL,
    ADM_SENHA VARCHAR(255) NOT NULL,
    ADM_ATIVO BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE PLA_PLANO (
    PLA_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLA_NOME VARCHAR(60) NOT NULL,
    PLA_VALOR DECIMAL(7,2) NOT NULL,
    PLA_DURACAO_MESES INT NOT NULL,
    PLA_SITUACAO VARCHAR(10) NOT NULL,
    -- Coluna calculada pelo H2: um único plano ativo com o mesmo nome (sem diferenciar maiúsculas) e a mesma duração.
    PLA_CHAVE_ATIVA VARCHAR(80) GENERATED ALWAYS AS (
        CASE WHEN PLA_SITUACAO = 'ATIVO' THEN LOWER(PLA_NOME) || '|' || CAST(PLA_DURACAO_MESES AS VARCHAR) END),
    CONSTRAINT UK_PLA_CHAVE_ATIVA UNIQUE (PLA_CHAVE_ATIVA),
    CONSTRAINT CK_PLA_VALOR CHECK (PLA_VALOR > 0),
    CONSTRAINT CK_PLA_DURACAO CHECK (PLA_DURACAO_MESES BETWEEN 1 AND 12),
    CONSTRAINT CK_PLA_SITUACAO CHECK (REGEXP_LIKE(PLA_SITUACAO, '^(ATIVO|INATIVO)$'))
);

CREATE TABLE ADP_ADESAO_PLANO (
    ADP_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    PLA_ID BIGINT NOT NULL REFERENCES PLA_PLANO(PLA_ID),
    ADP_PERIODICIDADE_MESES INT NOT NULL,
    ADP_INICIO DATE NOT NULL,
    ADP_ENCERRAMENTO DATE,
    ADP_SITUACAO VARCHAR(10) NOT NULL,
    -- Coluna calculada pelo H2: uma única adesão ativa por aluno.
    ADP_ALUNO_ATIVO BIGINT GENERATED ALWAYS AS (CASE WHEN ADP_SITUACAO = 'ATIVA' THEN ALU_ID END),
    CONSTRAINT UK_ADP_ALUNO_ATIVO UNIQUE (ADP_ALUNO_ATIVO),
    CONSTRAINT CK_ADP_PERIODICIDADE CHECK (ADP_PERIODICIDADE_MESES BETWEEN 1 AND 12),
    CONSTRAINT CK_ADP_SITUACAO CHECK (REGEXP_LIKE(ADP_SITUACAO, '^(ATIVA|ENCERRADA|CANCELADA)$')),
    CONSTRAINT CK_ADP_ENCERRAMENTO CHECK (
        (ADP_SITUACAO = 'ATIVA' AND ADP_ENCERRAMENTO IS NULL) OR
        (ADP_SITUACAO <> 'ATIVA' AND ADP_ENCERRAMENTO IS NOT NULL AND ADP_ENCERRAMENTO >= ADP_INICIO))
);
CREATE INDEX IX_ADP_ALUNO ON ADP_ADESAO_PLANO(ALU_ID,ADP_INICIO);
CREATE INDEX IX_ADP_PLANO ON ADP_ADESAO_PLANO(PLA_ID,ADP_SITUACAO);

CREATE TABLE MEN_MENSALIDADE (
    MEN_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADP_ID BIGINT NOT NULL REFERENCES ADP_ADESAO_PLANO(ADP_ID),
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    MEN_PERIODO_INICIO DATE NOT NULL,
    MEN_PERIODO_FIM DATE NOT NULL,
    MEN_VENCIMENTO DATE NOT NULL,
    MEN_VALOR DECIMAL(7,2) NOT NULL,
    -- ATRASADA não é gravada: é calculada pelo vencimento de uma mensalidade ABERTA.
    MEN_SITUACAO VARCHAR(10) NOT NULL,
    CONSTRAINT UK_MEN_ADESAO_PERIODO UNIQUE (ADP_ID,MEN_PERIODO_INICIO),
    CONSTRAINT CK_MEN_SITUACAO CHECK (REGEXP_LIKE(MEN_SITUACAO, '^(ABERTA|PAGA)$')),
    CONSTRAINT CK_MEN_VALOR CHECK (MEN_VALOR > 0),
    CONSTRAINT CK_MEN_PERIODO CHECK (MEN_PERIODO_FIM >= MEN_PERIODO_INICIO AND MEN_VENCIMENTO >= MEN_PERIODO_INICIO)
);
CREATE INDEX IX_MEN_ALUNO ON MEN_MENSALIDADE(ALU_ID,MEN_VENCIMENTO);
CREATE INDEX IX_MEN_SITUACAO ON MEN_MENSALIDADE(MEN_SITUACAO,MEN_VENCIMENTO);

CREATE TABLE PAG_PAGAMENTO (
    PAG_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MEN_ID BIGINT NOT NULL REFERENCES MEN_MENSALIDADE(MEN_ID),
    PAG_VALOR DECIMAL(9,2) NOT NULL,
    PAG_FORMA VARCHAR(20) NOT NULL,
    PAG_REGISTRO TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    PAG_SITUACAO VARCHAR(12) NOT NULL,
    PAG_ESTORNO TIMESTAMP(9) WITH TIME ZONE,
    PAG_MOTIVO_ESTORNO VARCHAR(250),
    -- Coluna calculada pelo H2: no máximo um pagamento confirmado por mensalidade.
    PAG_MENSALIDADE_CONFIRMADA BIGINT GENERATED ALWAYS AS (CASE WHEN PAG_SITUACAO = 'CONFIRMADO' THEN MEN_ID END),
    CONSTRAINT UK_PAG_CONFIRMADO UNIQUE (PAG_MENSALIDADE_CONFIRMADA),
    CONSTRAINT CK_PAG_VALOR CHECK (PAG_VALOR > 0),
    CONSTRAINT CK_PAG_FORMA CHECK (REGEXP_LIKE(PAG_FORMA, '^(DINHEIRO|PIX|CARTAO_DEBITO|CARTAO_CREDITO|BOLETO)$')),
    CONSTRAINT CK_PAG_SITUACAO CHECK (REGEXP_LIKE(PAG_SITUACAO, '^(CONFIRMADO|ESTORNADO)$')),
    CONSTRAINT CK_PAG_ESTORNO CHECK (
        (PAG_SITUACAO = 'CONFIRMADO' AND PAG_ESTORNO IS NULL AND PAG_MOTIVO_ESTORNO IS NULL) OR
        (PAG_SITUACAO = 'ESTORNADO' AND PAG_ESTORNO >= PAG_REGISTRO AND PAG_MOTIVO_ESTORNO IS NOT NULL))
);
CREATE INDEX IX_PAG_MENSALIDADE ON PAG_PAGAMENTO(MEN_ID,PAG_REGISTRO);

CREATE TABLE PRF_PROFISSIONAL (
    PRF_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRF_NOME VARCHAR(100) NOT NULL,
    PRF_CPF VARCHAR(11) NOT NULL,
    PRF_CREF VARCHAR(11) NOT NULL,
    PRF_CONTATO VARCHAR(100) NOT NULL,
    PRF_PROFESSOR BOOLEAN NOT NULL,
    PRF_PERSONAL_TRAINER BOOLEAN NOT NULL,
    PRF_SITUACAO VARCHAR(10) NOT NULL,
    CONSTRAINT UK_PRF_CPF UNIQUE (PRF_CPF),
    CONSTRAINT UK_PRF_CREF UNIQUE (PRF_CREF),
    CONSTRAINT CK_PRF_CLASSIFICACAO CHECK (PRF_PROFESSOR OR PRF_PERSONAL_TRAINER),
    CONSTRAINT CK_PRF_SITUACAO CHECK (REGEXP_LIKE(PRF_SITUACAO, '^(ATIVO|INATIVO)$'))
);
CREATE INDEX IX_PRF_NOME ON PRF_PROFISSIONAL(PRF_NOME);

CREATE TABLE PES_PROFISSIONAL_ESPECIALIDADE (
    PRF_ID BIGINT NOT NULL REFERENCES PRF_PROFISSIONAL(PRF_ID),
    PES_CHAVE VARCHAR(60) NOT NULL,
    PES_NOME VARCHAR(60) NOT NULL,
    PRIMARY KEY (PRF_ID,PES_CHAVE)
);

CREATE TABLE DSP_DISPONIBILIDADE_PROFISSIONAL (
    DSP_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRF_ID BIGINT NOT NULL REFERENCES PRF_PROFISSIONAL(PRF_ID),
    DSP_DIA VARCHAR(10) NOT NULL,
    DSP_INICIO TIME NOT NULL,
    DSP_FIM TIME NOT NULL,
    CONSTRAINT CK_DSP_DIA CHECK (REGEXP_LIKE(DSP_DIA, '^(MONDAY|TUESDAY|WEDNESDAY|THURSDAY|FRIDAY|SATURDAY|SUNDAY)$')),
    CONSTRAINT CK_DSP_HORARIO CHECK (DSP_INICIO < DSP_FIM)
);
CREATE INDEX IX_DSP_PROFISSIONAL ON DSP_DISPONIBILIDADE_PROFISSIONAL(PRF_ID,DSP_DIA);

CREATE TABLE VPA_VINCULO_PERSONAL_ALUNO (
    VPA_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRF_ID BIGINT NOT NULL REFERENCES PRF_PROFISSIONAL(PRF_ID),
    ALU_ID BIGINT NOT NULL REFERENCES ALU_ALUNO(ALU_ID),
    VPA_INICIO DATE NOT NULL,
    VPA_ENCERRAMENTO DATE,
    VPA_SITUACAO VARCHAR(10) NOT NULL,
    -- Colunas calculadas pelo H2: um único vínculo ativo entre o mesmo profissional e o mesmo aluno.
    VPA_PROFISSIONAL_ATIVO BIGINT GENERATED ALWAYS AS (CASE WHEN VPA_SITUACAO = 'ATIVO' THEN PRF_ID END),
    VPA_ALUNO_ATIVO BIGINT GENERATED ALWAYS AS (CASE WHEN VPA_SITUACAO = 'ATIVO' THEN ALU_ID END),
    CONSTRAINT UK_VPA_PAR_ATIVO UNIQUE (VPA_PROFISSIONAL_ATIVO,VPA_ALUNO_ATIVO),
    CONSTRAINT CK_VPA_SITUACAO CHECK (REGEXP_LIKE(VPA_SITUACAO, '^(ATIVO|ENCERRADO)$')),
    CONSTRAINT CK_VPA_ENCERRAMENTO CHECK (
        (VPA_SITUACAO = 'ATIVO' AND VPA_ENCERRAMENTO IS NULL) OR
        (VPA_SITUACAO <> 'ATIVO' AND VPA_ENCERRAMENTO IS NOT NULL AND VPA_ENCERRAMENTO >= VPA_INICIO))
);
CREATE INDEX IX_VPA_PROFISSIONAL ON VPA_VINCULO_PERSONAL_ALUNO(PRF_ID,VPA_SITUACAO);
CREATE INDEX IX_VPA_ALUNO ON VPA_VINCULO_PERSONAL_ALUNO(ALU_ID,VPA_SITUACAO);
